/// `Joining_Type` = `Left_Joining` (`L`).
pub(super) const JOIN_LEFT: u16 = 1 << 2;
/// `Joining_Type` = `Dual_Joining` (`D`).
pub(super) const JOIN_DUAL: u16 = 1 << 3;
/// `Joining_Type` = `Right_Joining` (`R`).
pub(super) const JOIN_RIGHT: u16 = 1 << 4;
/// `Joining_Type` = Transparent (`T`).
pub(super) const JOIN_TRANSPARENT: u16 = 1 << 5;
/// `Script` = Greek.
pub(super) const GREEK: u16 = 1 << 6;
/// `Script` = Hebrew.
