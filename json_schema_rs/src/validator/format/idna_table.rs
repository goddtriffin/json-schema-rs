//! IDNA2008 code point table (RFC 5892) for the `hostname` and `idn-hostname` formats.
//!
//! Every non-ASCII code point whose IDNA2008 derived property is `PVALID`, `CONTEXTJ` or
//! `CONTEXTO` appears in exactly one range; every other non-ASCII code point (`DISALLOWED`,
//! `UNASSIGNED`) is absent. Ranges are sorted, disjoint, and merged when adjacent code points
//! share the same flags. ASCII is handled by the caller.
//!
//! Derived from the Unicode 17.0 Character Database by the RFC 5892 section 3 algorithm:
//! the section 2.6 exceptions first, then `Unassigned` (general category `Cn`, excluding
//! noncharacters), `LDH`, `JoinControl` (`CONTEXTJ`), `Unstable` (`Changes_When_NFKC_Casefolded`),
//! `IgnorableProperties` (`Default_Ignorable_Code_Point`, `White_Space`,
//! `Noncharacter_Code_Point`), `IgnorableBlocks`, `OldHangulJamo` (`Hangul_Syllable_Type` L, V,
//! T), and finally `LetterDigits` (general category Ll, Lu, Lo, Nd, Lm, Mn, Mc) as `PVALID`.
//!
//! Flags carry the properties the RFC 5891 / RFC 5892 contextual rules read: the general
//! category `M` (a label must not begin with a combining mark), `Canonical_Combining_Class`
//! Virama (ZERO WIDTH JOINER / NON-JOINER), `Joining_Type` (ZERO WIDTH NON-JOINER), and the
//! scripts Greek, Hebrew, and Hiragana / Katakana / Han.
//!
//! The rows of [`IDNA_VALID`] are generated by `research/scripts/gen_idna_table.py`; do not edit
//! them by hand.

/// General category `Mn`, `Mc` or `Me`.
pub(super) const MARK: u16 = 1 << 0;
/// `Canonical_Combining_Class` = Virama (9).
