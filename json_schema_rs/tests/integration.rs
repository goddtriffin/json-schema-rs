/// One `pub mod <name> { ... }` per `(name, setting)`, each holding the code generated for a
/// required `uniqueItems` string array with that `UniqueItemsType`.
fn unique_items_set_modules(modules: &[(&str, UniqueItemsType)]) -> Vec<u8> {
    let schema_json: &str = r#"{"type":"object","properties":{"tags":{"type":"array","items":{"type":"string"},"uniqueItems":true}},"required":["tags"]}"#;
    let mut lib_rs: Vec<u8> = Vec::new();
    for (name, setting) in modules {
        let settings: CodeGenSettings = CodeGenSettings::builder().unique_items(*setting).build();
        let code: Vec<u8> = generate_single(schema_json, &settings);
        lib_rs.extend_from_slice(format!("pub mod {name} {{\n").as_bytes());
        lib_rs.extend_from_slice(&code);
        lib_rs.extend_from_slice(b"}\n");
    }
    lib_rs
}

/// Like [`unique_items_set_modules`], for generated item types: a string enum, a closed struct
/// reaching a struct with typed unknown keys, a string / integer union, and a struct with a
/// float field (which stays `Vec`).
fn unique_items_generated_item_modules(modules: &[(&str, UniqueItemsType)]) -> Vec<u8> {
    let schema_json: &str = r##"{"type":"object","properties":{"colors":{"type":"array","items":{"enum":["red","green","blue"]},"uniqueItems":true},"ids":{"type":"array","items":{"oneOf":[{"type":"string"},{"type":"integer"}]},"uniqueItems":true},"points":{"type":"array","items":{"$ref":"#/$defs/Point"},"uniqueItems":true},"readings":{"type":"array","items":{"$ref":"#/$defs/Reading"},"uniqueItems":true}},"required":["colors","ids","points","readings"],"$defs":{"Point":{"type":"object","properties":{"x":{"type":"integer"},"y":{"type":"integer"},"tag":{"$ref":"#/$defs/Tag"}},"required":["x","y"],"additionalProperties":false},"Tag":{"type":"object","properties":{"name":{"type":"string"}},"additionalProperties":{"type":"boolean"}},"Reading":{"type":"object","properties":{"value":{"type":"number"}},"required":["value"],"additionalProperties":false}}}"##;
    let mut lib_rs: Vec<u8> = Vec::new();
    for (name, setting) in modules {
        let settings: CodeGenSettings = CodeGenSettings::builder().unique_items(*setting).build();
        let code: Vec<u8> = generate_single(schema_json, &settings);
        lib_rs.extend_from_slice(format!("pub mod {name} {{\n").as_bytes());
        lib_rs.extend_from_slice(&code);
        lib_rs.extend_from_slice(b"}\n");
    }
    lib_rs
}

/// Generates code for one schema and returns its per-schema buffer.
fn generate_single(schema_json: &str, settings: &CodeGenSettings) -> Vec<u8> {
    let schema: Schema = Schema::try_from(schema_json).expect("parse schema");
    let output = generate_rust(&[schema], settings).expect("generate");
    output.per_schema[0].clone()
}

