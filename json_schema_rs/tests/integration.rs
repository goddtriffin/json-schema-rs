/// Validator verdict for `instance` against the parsed `schema_json`.
fn public_api_is_valid(schema_json: &str, instance: &serde_json::Value) -> bool {
    let schema: Schema = Schema::try_from(schema_json).expect("parse schema");
    validate(&schema, instance).is_ok()
}

