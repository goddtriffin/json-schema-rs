//! Rendering of the differential report as `results.md`.
//!
//! Output is a pure function of the [`DifferentialReport`], so it is byte-identical across
//! runs on the same inputs. Long lists are wrapped in `<details>` blocks.

use crate::analysis::{
    DisagreementCase, DisagreementTest, ErroredTest, ImplementationStats, OurFindings, OurStats,
    SectionReport, TestRecord, UnsupportedReason, WrongWithMajority, test_count,
};
use crate::messages::{MessageCase, ToolOutcome, ToolOutput};
use crate::report::Verdict;
use crate::{DifferentialReport, DraftReport, FixtureReport};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// Longest schema or instance (in pretty-printed lines) rendered in full in the message section.
const MAX_JSON_LINES: usize = 30;
/// Most message lines rendered per tool in the message section (`results.json` keeps all).
const MAX_MESSAGE_LINES: usize = 40;

/// Render the whole report.
#[must_use]
pub fn render(report: &DifferentialReport) -> String {
    let mut out: String = String::new();
    render_header(&mut out, report);
    render_summary(&mut out, report);
    render_unsupported(
        &mut out,
        "Unsupported features (suite)",
        "Every suite test our harness skipped, grouped by reason and sorted by impact. This is the coverage roadmap signal.",
        &report.unsupported,
    );
    render_drafts(&mut out, report);
    render_fixtures(&mut out, report);
    render_messages(&mut out, &report.messages);
    out
}

/// Escape text for a markdown table cell.
#[must_use]
pub fn cell(text: &str) -> String {
    text.replace('\\', "\\\\")
        .replace('|', "\\|")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace(['\r', '\n'], " ")
}

fn validity(valid: bool) -> &'static str {
    if valid { "valid" } else { "invalid" }
}

fn optional_validity(valid: Option<bool>) -> &'static str {
    valid.map_or("none", validity)
}

/// One-word rendering of a verdict.
#[must_use]
pub fn verdict_word(verdict: &Verdict) -> &'static str {
    match verdict {
        Verdict::Valid => "valid",
        Verdict::Invalid => "invalid",
        Verdict::Skipped { .. } => "skipped",
        Verdict::Errored { .. } => "errored",
    }
}

fn implementation_label(report: &DifferentialReport, id: &str) -> String {
    if id == report.ours {
        format!("`{id}` (ours)")
    } else {
        format!("`{id}`")
    }
}

/// Implementation ids with ours first, then the rest in id order.
fn ordered_ids<'a, I>(ours: &str, ids: I) -> Vec<String>
where
    I: Iterator<Item = &'a String>,
{
    let mut rest: Vec<String> = ids.filter(|id: &&String| *id != ours).cloned().collect();
    rest.sort();
    let mut ordered: Vec<String> = vec![ours.to_string()];
    ordered.extend(rest);
    ordered
}

fn render_header(out: &mut String, report: &DifferentialReport) {
    out.push_str("# Differential testing results\n\n");
    let _ = writeln!(
        out,
        "Generated by `differential_report` from Bowtie reports over the official JSON Schema Test Suite and the benchmark fixtures, plus an in-process error-message comparison. Our implementation: `{}`.\n",
        report.ours
    );
    out.push_str("Definitions: **compliance** = tests passed / all tests; **coverage** = tests we ran / all tests (skips are unsupported features); **correctness** = tests passed / tests we ran with a real verdict; **majority** = strict majority of competitors with a real verdict (skipped/errored competitors do not vote; ties are no consensus).\n\n");
    out.push_str("## Implementations\n\n| Id | Name | Language | Version |\n|---|---|---|---|\n");
    for (id, info) in &report.implementations {
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} |",
            implementation_label(report, id),
            cell(&info.name),
            cell(&info.language),
            cell(info.version.as_deref().unwrap_or("unknown"))
        );
    }
    out.push('\n');
}

fn our_stats_row(label: &str, tests: u64, ours: &OurStats) -> String {
    format!(
        "| {label} | {tests} | {} | {} | {} | {} | {} | {} | {} | {} |",
        ours.compliance.display(),
        ours.coverage.display(),
        ours.correctness.display(),
        ours.tally.failed,
        ours.tally.skipped,
        ours.tally.errored,
        ours.disagreements_with_majority,
        ours.wrong_vs_expected
    )
}

const OUR_STATS_HEADER: &str = "| Draft | Tests | Compliance | Coverage | Correctness | Failed | Skipped (unsupported) | Errored | Disagree with majority | Wrong vs expected |\n|---|---|---|---|---|---|---|---|---|---|\n";

fn render_summary(out: &mut String, report: &DifferentialReport) {
    out.push_str("## Summary\n\n### Our results per draft (non-optional suite)\n\n");
    out.push_str(OUR_STATS_HEADER);
    for (row, draft) in report.summary.drafts.iter().zip(&report.drafts) {
        out.push_str(&our_stats_row(&row.draft, draft.required.tests, &row.ours));
        out.push('\n');
    }
    out.push('\n');
    out.push_str("### Compliance per implementation (non-optional suite, all drafts)\n\n");
    render_stats_table(out, report, &report.summary.suite);
    if let Some(optional) = &report.summary.optional_suite {
        out.push_str("### Compliance per implementation (optional suite, all drafts)\n\n");
        render_stats_table(out, report, optional);
    } else {
        out.push_str("_No optional-suite (`tests/<draft>/optional/`) tests were reported._\n\n");
    }
    out.push_str("### Agreement with the fixture manifest per implementation (all fixtures)\n\n");
    render_stats_table(out, report, &report.summary.fixtures);
}

fn render_stats_table(
    out: &mut String,
    report: &DifferentialReport,
    stats: &BTreeMap<String, ImplementationStats>,
) {
    out.push_str("| Implementation | Compliance | Passed | Failed | Skipped | Errored | Total |\n|---|---|---|---|---|---|---|\n");
    for id in ordered_ids(&report.ours, stats.keys()) {
        let Some(s) = stats.get(&id) else {
            continue;
        };
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} | {} | {} |",
            implementation_label(report, &id),
            s.compliance.display(),
            s.tally.passed,
            s.tally.failed,
            s.tally.skipped,
            s.tally.errored,
            s.tally.total
        );
    }
    out.push('\n');
}

fn render_unsupported(out: &mut String, title: &str, intro: &str, reasons: &[UnsupportedReason]) {
    let _ = writeln!(out, "## {title}\n\n{intro}\n");
    if reasons.is_empty() {
        out.push_str("_No tests were skipped._\n\n");
        return;
    }
    out.push_str("| Reason | Tests | Cases | By group |\n|---|---|---|---|\n");
    for reason in reasons {
        let by_group: Vec<String> = reason
            .by_group
            .iter()
            .map(|(group, count): (&String, &u64)| format!("{group}: {count}"))
            .collect();
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} |",
            cell(&reason.reason),
            reason.tests,
            reason.cases,
            cell(&by_group.join(", "))
        );
    }
    out.push('\n');
}

fn render_drafts(out: &mut String, report: &DifferentialReport) {
    out.push_str("## Per-draft results\n\n");
    for draft in &report.drafts {
        render_draft(out, report, draft);
    }
}

fn render_draft(out: &mut String, report: &DifferentialReport, draft: &DraftReport) {
    let _ = writeln!(
        out,
        "### {}\n\nDialect: `{}`.\n",
        draft.draft, draft.dialect
    );
    if draft.did_fail_fast {
        out.push_str("**Warning:** Bowtie stopped this run early (fail-fast); unreported tests count as errored.\n\n");
    }
    if draft.unmapped_cases > 0 {
        let _ = writeln!(
            out,
            "_{} case(s) could not be mapped back to a suite file; they count as non-optional._\n",
            draft.unmapped_cases
        );
    }
    out.push_str("Non-optional suite:\n\n");
    render_stats_table(out, report, &draft.required.implementations);
    if let Some(optional) = &draft.optional {
        out.push_str("Optional suite:\n\n");
        render_stats_table(out, report, &optional.implementations);
    }
    render_findings(out, &draft.findings, true);
}

fn render_findings(out: &mut String, findings: &OurFindings, show_file: bool) {
    render_disagreements(
        out,
        "Disagreements with the competitor majority",
        &findings.disagreements_with_majority,
        show_file,
    );
    render_disagreements(
        out,
        "Wrong vs. expected with no competitor consensus",
        &findings.wrong_without_consensus,
        show_file,
    );
    render_wrong_with_majority(out, &findings.wrong_with_majority, show_file);
    render_errored(out, &findings.errored);
}

fn file_label(file: Option<&str>, optional: bool) -> String {
    match (file, optional) {
        (Some(f), _) => format!("`{}`", cell(f)),
        (None, true) => "(optional, unmapped)".to_string(),
        (None, false) => "(unmapped)".to_string(),
    }
}

fn render_disagreements(
    out: &mut String,
    title: &str,
    cases: &[DisagreementCase],
    show_file: bool,
) {
    let total: u64 = test_count(cases);
    let _ = writeln!(out, "**{title}: {total}**\n");
    if cases.is_empty() {
        return;
    }
    let _ = writeln!(out, "<details><summary>{title} ({total})</summary>\n");
    out.push_str("One row per case; each test lists its expected verdict. Majority is `agreeing/voters`.\n\n");
    if show_file {
        out.push_str(
            "| File | Case | Tests (expected) | Majority | Triage |\n|---|---|---|---|---|\n",
        );
    } else {
        out.push_str("| Case | Tests (expected) | Majority | Triage |\n|---|---|---|---|\n");
    }
    for case in cases {
        let tests: Vec<String> = case
            .tests
            .iter()
            .map(|t: &DisagreementTest| match t.expected {
                Some(e) => format!("{} ({})", cell(&t.test_description), validity(e)),
                None => format!("{} (ours: {})", cell(&t.test_description), validity(t.ours)),
            })
            .collect();
        let majorities: BTreeSet<String> = case
            .tests
            .iter()
            .map(|t: &DisagreementTest| {
                let size: String = format!("{}/{}", t.agreeing, t.voters);
                match (t.expected, t.majority) {
                    (None, Some(v)) => format!("{} {size}", validity(v)),
                    _ => size,
                }
            })
            .collect();
        let file: String = if show_file {
            format!("{} | ", file_label(case.file.as_deref(), case.optional))
        } else {
            String::new()
        };
        let _ = writeln!(
            out,
            "| {file}{} | {} | {} | {} |",
            cell(&case.case_description),
            tests.join("; "),
            majorities.into_iter().collect::<Vec<String>>().join(", "),
            case.triage.label()
        );
    }
    out.push_str("\n</details>\n\n");
}

fn render_wrong_with_majority(out: &mut String, list: &[WrongWithMajority], show_file: bool) {
    let total: u64 = list.iter().map(|w: &WrongWithMajority| w.tests).sum();
    let _ = writeln!(
        out,
        "**Wrong vs. expected but agreeing with the competitor majority: {total}**\n"
    );
    if list.is_empty() {
        return;
    }
    let _ = writeln!(
        out,
        "<details><summary>Wrong vs. expected, majority agrees with us (aggregated per file)</summary>\n"
    );
    out.push_str("| File | Tests | Majority (agreeing/voters: tests) |\n|---|---|---|\n");
    for w in list {
        let majority: Vec<String> = w
            .majority
            .iter()
            .map(|(size, count): (&String, &u64)| format!("{size}: {count}"))
            .collect();
        let file: String = if show_file {
            file_label(w.file.as_deref(), w.optional)
        } else {
            cell(&w.group)
        };
        let _ = writeln!(out, "| {file} | {} | {} |", w.tests, majority.join(", "));
    }
    out.push_str("\n</details>\n\n");
}

fn render_errored(out: &mut String, list: &[ErroredTest]) {
    let _ = writeln!(out, "**Tests our harness errored on: {}**\n", list.len());
    if list.is_empty() {
        return;
    }
    let _ = writeln!(
        out,
        "<details><summary>Errored tests ({})</summary>\n",
        list.len()
    );
    out.push_str("| File | Case | Test | Error |\n|---|---|---|---|\n");
    for e in list {
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} |",
            e.file
                .as_deref()
                .map_or_else(|| "(unmapped)".to_string(), cell),
            cell(&e.case_description),
            cell(&e.test_description),
            cell(&e.message)
        );
    }
    out.push_str("\n</details>\n\n");
}

fn render_fixtures(out: &mut String, report: &DifferentialReport) {
    out.push_str("## Fixtures\n\nReal-world and massive schemas from `json_schema_rs_benchmark/fixtures/`, run through Bowtie (`bowtie validate`). Expected verdicts come from the manifest's valid/invalid instance lists.\n\n");
    for fixture in &report.fixtures {
        render_fixture(out, report, fixture);
    }
    render_unsupported(
        out,
        "Unsupported features (fixtures)",
        "Every fixture instance our harness skipped, grouped by reason.",
        &report.fixture_unsupported,
    );
}

fn render_fixture(out: &mut String, report: &DifferentialReport, fixture: &FixtureReport) {
    let _ = writeln!(out, "### {}\n", fixture.id);
    render_stats_table(out, report, &fixture.section.implementations);
    render_verdict_grid(out, report, &fixture.section, &fixture.instances);
    render_findings(out, &fixture.findings, false);
}

fn render_verdict_grid(
    out: &mut String,
    report: &DifferentialReport,
    section: &SectionReport,
    instances: &[TestRecord],
) {
    let ids: Vec<String> = ordered_ids(&report.ours, section.implementations.keys());
    out.push_str("<details><summary>Verdict per instance</summary>\n\n| Instance | Expected |");
    for id in &ids {
        let _ = write!(out, " {} |", implementation_label(report, id));
    }
    out.push_str("\n|---|---|");
    out.push_str(&"---|".repeat(ids.len()));
    out.push('\n');
    for record in instances {
        let _ = write!(
            out,
            "| `{}` | {} |",
            cell(&record.test_description),
            optional_validity(record.expected)
        );
        for id in &ids {
            let rendered: String = match record.verdicts.get(id) {
                Some(verdict) => {
                    let word: &str = verdict_word(verdict);
                    match (verdict.validity(), record.expected) {
                        (Some(v), Some(e)) if v != e => format!("**{word} (wrong)**"),
                        _ => word.to_string(),
                    }
                }
                None => "-".to_string(),
            };
            let _ = write!(out, " {rendered} |");
        }
        out.push('\n');
    }
    out.push_str("\n</details>\n\n");
}

fn json_block(value: &serde_json::Value) -> String {
    let pretty: String = serde_json::to_string_pretty(value).unwrap_or_else(|_| value.to_string());
    let lines: Vec<&str> = pretty.lines().collect();
    if lines.len() <= MAX_JSON_LINES {
        format!("```json\n{pretty}\n```\n")
    } else {
        format!(
            "```json\n{}\n```\n_({} more lines omitted)_\n",
            lines[..MAX_JSON_LINES].join("\n"),
            lines.len() - MAX_JSON_LINES
        )
    }
}

/// Render a schema or instance: its fixtures-relative path when it has one, and its JSON
/// when it is embedded.
fn render_document(
    out: &mut String,
    label: &str,
    path: Option<&str>,
    value: Option<&serde_json::Value>,
) {
    match (path, value) {
        (Some(p), Some(v)) => {
            let _ = writeln!(out, "{label} (`{p}`):\n");
            out.push_str(&json_block(v));
        }
        (Some(p), None) => {
            let _ = writeln!(
                out,
                "{label}: `{p}` (relative to the fixtures directory; not embedded)."
            );
        }
        (None, Some(v)) => {
            let _ = writeln!(out, "{label}:\n");
            out.push_str(&json_block(v));
        }
        (None, None) => {
            let _ = writeln!(out, "{label}: not recorded.");
        }
    }
    out.push('\n');
}

fn outcome_word(outcome: ToolOutcome) -> &'static str {
    match outcome {
        ToolOutcome::Valid => "valid",
        ToolOutcome::Invalid => "invalid",
        ToolOutcome::Error => "error",
    }
}

fn render_tool_output(out: &mut String, tool: &ToolOutput) {
    let _ = writeln!(
        out,
        "**{}**: {} ({} message line(s))\n",
        tool.tool,
        outcome_word(tool.outcome),
        tool.messages.len()
    );
    if tool.messages.is_empty() {
        return;
    }
    let shown: &[String] = &tool.messages[..tool.messages.len().min(MAX_MESSAGE_LINES)];
    let _ = writeln!(out, "```text\n{}\n```", shown.join("\n"));
    if tool.messages.len() > MAX_MESSAGE_LINES {
        let _ = writeln!(
            out,
            "_({} more lines in results.json)_",
            tool.messages.len() - MAX_MESSAGE_LINES
        );
    }
    out.push('\n');
}

fn render_messages(out: &mut String, cases: &[MessageCase]) {
    out.push_str("## Error messages side by side\n\nIn-process comparison of our messages against the `jsonschema` and `boon` crates. Curated set: for each non-optional `tests/draft2020-12/*.json` suite file, the first invalid test whose schema we strict-parse and whose instance we correctly reject; plus every invalid instance of every benchmark fixture.\n\n");
    if cases.is_empty() {
        out.push_str("_No cases selected._\n");
        return;
    }
    for (index, case) in cases.iter().enumerate() {
        let _ = writeln!(
            out,
            "### {}. {} — {}\n",
            index + 1,
            case.source,
            case.title.replace(['\r', '\n'], " ")
        );
        render_document(
            out,
            "Schema",
            case.schema_path.as_deref(),
            case.schema.as_ref(),
        );
        render_document(
            out,
            "Instance",
            case.instance_path.as_deref(),
            case.instance.as_ref(),
        );
        for tool in &case.outputs {
            render_tool_output(out, tool);
        }
    }
}

