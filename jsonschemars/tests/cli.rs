#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, json_schema_rs_macro::ToJsonSchema)]
pub enum Level {
    #[json_schema(value = "high")]
    High,
    #[json_schema(value = 1)]
    N1,
    #[json_schema(value = 2.5)]
    N2Point5,
    #[json_schema(value = true)]
    True,
}

impl Serialize for Level {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        let value: serde_json::Value = match self {
            Self::High => serde_json::json!("high"),
            Self::N1 => serde_json::json!(1),
            Self::N2Point5 => serde_json::json!(2.5),
            Self::True => serde_json::json!(true),
        };
        value.serialize(serializer)
    }
}

impl<'de> Deserialize<'de> for Level {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value: serde_json::Value = serde_json::Value::deserialize(deserializer)?;
        if json_schema_rs::json_equal(&value, &serde_json::json!("high")) {
            return Ok(Self::High);
        }
        if json_schema_rs::json_equal(&value, &serde_json::json!(1)) {
            return Ok(Self::N1);
        }
        if json_schema_rs::json_equal(&value, &serde_json::json!(2.5)) {
            return Ok(Self::N2Point5);
        }
        if json_schema_rs::json_equal(&value, &serde_json::json!(true)) {
            return Ok(Self::True);
        }
        Err(serde::de::Error::custom(format!("value {value} not in enum (allowed: {})", "\"high\", 1, 2.5, true")))
    }
}

