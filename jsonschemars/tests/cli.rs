/// Runs `jsonschemars generate rust -o <dir> <extra_args> schema.json` on `schema_json`;
/// returns whether it exited successfully and the generated `schema.rs` (empty when missing).
fn cli_generate_single(schema_json: &str, extra_args: &[&str]) -> (bool, String) {
    let temp_dir = tempfile::tempdir().expect("temp dir");
    let schema_path = temp_dir.path().join("schema.json");
    std::fs::write(&schema_path, schema_json).expect("write schema");
    let out_dir = tempfile::tempdir().expect("temp out dir");
    let output = Command::new(jsonschemars_bin())
        .args([
            "generate",
            "rust",
            "--cgs-self-validating",
            "false",
            "-o",
            out_dir.path().to_str().unwrap(),
        ])
        .args(if extra_args.contains(&"--cgs-constrained-newtypes") {
            &[][..]
        } else {
            &["--cgs-constrained-newtypes", "false"][..]
        })
        .args(extra_args)
        .arg(schema_path.to_str().unwrap())
        .output()
        .expect("run jsonschemars");
    let generated: String =
        std::fs::read_to_string(out_dir.path().join("schema.rs")).unwrap_or_default();
    (output.status.success(), generated)
}

