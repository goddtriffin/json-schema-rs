//! Integration test: the `jsonschemars` binary.

use std::collections::BTreeMap;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::process::Stdio;

fn jsonschemars_bin() -> PathBuf {
    PathBuf::from(env!("CARGO_BIN_EXE_jsonschemars"))
}

#[test]
fn cli_generate_rust_single_file_to_output_dir() {
    let schema_json =
        r#"{"type":"object","properties":{"id":{"type":"string"}},"required":["id"]}"#;
    let temp_dir = tempfile::tempdir().expect("temp dir");
    let schema_path = temp_dir.path().join("schema.json");
    std::fs::write(&schema_path, schema_json).expect("write schema");
    let out_dir = tempfile::tempdir().expect("temp out dir");
    let output = Command::new(jsonschemars_bin())
        .args([
            "generate",
            "rust",
            "--cgs-self-validating",
            "false",
            "--cgs-constrained-newtypes",
            "false",
            "-o",
            out_dir.path().to_str().unwrap(),
            schema_path.to_str().unwrap(),
        ])
        .output()
        .expect("run jsonschemars");
    assert!(
        output.status.success(),
        "exit success: stderr={}",
        String::from_utf8_lossy(&output.stderr)
    );
    let out_path = out_dir.path().join("schema.rs");
    let actual = std::fs::read_to_string(&out_path).expect("read output");
    let expected = r"//! Generated by json-schema-rs. Do not edit manually.

use serde::Serialize;
use std::collections::BTreeMap;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, json_schema_rs_macro::Deserialize, json_schema_rs_macro::ToJsonSchema)]
pub struct Root {
    pub id: String,
    #[serde(flatten)]
    pub additional: BTreeMap<String, serde_json::Value>,
}

";
    assert_eq!(expected, actual);
}

