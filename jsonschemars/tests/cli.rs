/// The same schema files generate the same code wherever they are: in different directories,
/// named by different paths, from a different working directory.
#[test]
fn cli_generate_rust_output_does_not_depend_on_the_input_location() {
    let a_json =
        r#"{"type":"object","properties":{"pet":{"$ref":"sub/b.json"}},"required":["pet"]}"#;
    let b_json = r#"{"title":"Pet","type":"object","properties":{"kind":{"anyOf":[{"type":"string","maxLength":3},{"type":"string","pattern":"^long"}]}}}"#;
    let generate = |nesting: &str| -> (bool, Vec<(String, String)>) {
        let temp_dir = tempfile::tempdir().expect("temp dir");
        let root: PathBuf = temp_dir.path().join(nesting);
        fs::create_dir_all(root.join("sub")).expect("create dirs");
        fs::write(root.join("a.json"), a_json).expect("write a");
        fs::write(root.join("sub").join("b.json"), b_json).expect("write b");
        let out_dir = tempfile::tempdir().expect("temp out dir");
        let output = Command::new(jsonschemars_bin())
            .current_dir(temp_dir.path())
            .args(["generate", "rust", "-o"])
            .arg(out_dir.path())
            .arg(PathBuf::from(nesting).join("a.json"))
            .arg(root.join("sub").join("b.json"))
            .output()
            .expect("run jsonschemars");
        let mut files: Vec<(String, String)> = walkdir_files(out_dir.path());
        files.sort();
        (output.status.success(), files)
    };
    let expected: (bool, Vec<(String, String)>) = generate("x");
    let actual: (bool, Vec<(String, String)>) = generate("deeply/nested/elsewhere");
    assert_eq!(expected, actual);
}

/// Every file under `dir`, as (path relative to `dir`, content).
fn walkdir_files(dir: &Path) -> Vec<(String, String)> {
    let mut out: Vec<(String, String)> = Vec::new();
    let mut stack: Vec<PathBuf> = vec![dir.to_path_buf()];
    while let Some(current) = stack.pop() {
        for entry in fs::read_dir(&current).expect("read dir") {
            let path: PathBuf = entry.expect("dir entry").path();
            if path.is_dir() {
                stack.push(path);
            } else {
                let relative: String = path
                    .strip_prefix(dir)
                    .expect("under dir")
                    .to_string_lossy()
                    .replace('\\', "/");
                out.push((relative, fs::read_to_string(&path).expect("read file")));
            }
        }
    }
    out
}

